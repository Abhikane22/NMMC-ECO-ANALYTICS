
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd

from src.config import YEARS, REPORTS_DIR, CHARTS_DIR


# ---------------------------------------------------------
# 1. CONFIGURATION
# ---------------------------------------------------------

ANNUAL_FILE = REPORTS_DIR / "ecological_annual_raster_statistics.csv"
CHANGE_FILE = REPORTS_DIR / "ecological_temporal_changes_1994_2024.csv"
TREND_FILE = REPORTS_DIR / "ecological_temporal_trends.csv"

OPTICAL_INDICATORS = ["NDVI", "NDWI", "MNDWI"]


# ---------------------------------------------------------
# 2. LOAD REPORTS
# ---------------------------------------------------------

def load_analysis_reports():
    """Load reports generated by ecological_analysis.py."""

    required_files = [
        ANNUAL_FILE,
        CHANGE_FILE,
        TREND_FILE,
    ]

    for file_path in required_files:
        if not file_path.exists():
            raise FileNotFoundError(
                f"Required report not found: {file_path}\n"
                "Run python3 -m src.ecological_analysis first."
            )

    annual = pd.read_csv(ANNUAL_FILE)
    changes = pd.read_csv(CHANGE_FILE)
    trends = pd.read_csv(TREND_FILE)

    required_annual = {"year", "indicator", "mean", "std"}
    required_changes = {"indicator", "mean_change"}
    required_trends = {
        "indicator",
        "slope_per_decade",
        "r_squared_descriptive",
    }

    if not required_annual.issubset(annual.columns):
        raise ValueError(
            f"Annual report missing columns: "
            f"{required_annual - set(annual.columns)}"
        )

    if not required_changes.issubset(changes.columns):
        raise ValueError(
            f"Change report missing columns: "
            f"{required_changes - set(changes.columns)}"
        )

    if not required_trends.issubset(trends.columns):
        raise ValueError(
            f"Trend report missing columns: "
            f"{required_trends - set(trends.columns)}"
        )

    CHARTS_DIR.mkdir(parents=True, exist_ok=True)

    return annual, changes, trends


# ---------------------------------------------------------
# 3. SAVE CHART
# ---------------------------------------------------------

def save_chart(fig, filename):
    """Save a publication-quality chart."""

    output_path = CHARTS_DIR / filename

    fig.tight_layout()
    fig.savefig(
        output_path,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(fig)

    print(f"Saved: {output_path.name}")


# ---------------------------------------------------------
# 4. INDICATOR TEMPORAL TRENDS
# ---------------------------------------------------------

def plot_indicator_trends(annual):
    """
    Generate one temporal line chart per indicator.

    Each chart displays the annual mean for 1994, 2004,
    2014 and 2024.
    """

    for indicator in annual["indicator"].unique():

        subset = annual[
            annual["indicator"] == indicator
        ].sort_values("year")

        fig, ax = plt.subplots(figsize=(9, 5))

        ax.plot(
            subset["year"],
            subset["mean"],
            marker="o",
            linewidth=2,
        )

        ax.set_title(
            f"{indicator} Temporal Variation (1994–2024)",
            fontsize=14,
            fontweight="bold",
        )

        ax.set_xlabel("Year")

        ax.set_ylabel(
            "Land Surface Temperature (°C)"
            if indicator == "LST_C"
            else (
                "UTFVI"
                if indicator == "UTFVI"
                else f"{indicator} Mean"
            )
        )

        ax.set_xticks(YEARS)
        ax.grid(True, linestyle="--", alpha=0.4)

        save_chart(
            fig,
            f"{indicator}_temporal_trend.png",
        )


# ---------------------------------------------------------
# 5. LST DISTRIBUTION
# ---------------------------------------------------------

def plot_lst_distribution(annual):
    """
    Plot LST mean and standard deviation across years.
    """

    subset = annual[
        annual["indicator"] == "LST_C"
    ].sort_values("year")

    if subset.empty:
        print("Warning: LST data not found.")
        return

    fig, ax = plt.subplots(figsize=(9, 5))

    ax.errorbar(
        subset["year"],
        subset["mean"],
        yerr=subset["std"],
        marker="o",
        capsize=5,
        linewidth=2,
    )

    ax.set_title(
        "NMMC Land Surface Temperature Distribution",
        fontsize=14,
        fontweight="bold",
    )

    ax.set_xlabel("Year")
    ax.set_ylabel("LST (°C)")
    ax.set_xticks(YEARS)
    ax.grid(True, linestyle="--", alpha=0.4)

    save_chart(
        fig,
        "LST_mean_with_standard_deviation.png",
    )


# ---------------------------------------------------------
# 6. OPTICAL INDEX CHANGES
# ---------------------------------------------------------

def plot_optical_index_changes(changes):
    """
    Compare endpoint changes for selected optical indices.

    NDBI is excluded because it is an exact negative of
    NDMI in the current dataset.
    """

    optical = changes[
        changes["indicator"].isin(OPTICAL_INDICATORS)
    ].copy()

    if optical.empty:
        print("Warning: No optical change data found.")
        return

    fig, ax = plt.subplots(figsize=(9, 5))

    bars = ax.bar(
        optical["indicator"],
        optical["mean_change"],
    )

    ax.axhline(0, linewidth=0.8)

    ax.bar_label(
        bars,
        fmt="%.4f",
        padding=4,
    )

    ax.set_title(
        "Change in Optical Indices (1994–2024)",
        fontsize=14,
        fontweight="bold",
    )

    ax.set_xlabel("Optical Index")
    ax.set_ylabel("Change in Mean Index Value")
    ax.grid(axis="y", linestyle="--", alpha=0.4)

    save_chart(
        fig,
        "optical_index_absolute_changes.png",
    )


# ---------------------------------------------------------
# 7. LST TEMPORAL CHANGE
# ---------------------------------------------------------

def plot_lst_change(changes):
    """Plot the difference in mean LST between endpoints."""

    lst = changes[
        changes["indicator"] == "LST_C"
    ]

    if lst.empty:
        print("Warning: LST change data not found.")
        return

    lst_change = float(
        lst.iloc[0]["mean_change"]
    )

    fig, ax = plt.subplots(figsize=(7, 5))

    bars = ax.bar(
        ["1994–2024"],
        [lst_change],
    )

    ax.bar_label(
        bars,
        fmt="%.2f °C",
        padding=5,
    )

    ax.axhline(0, linewidth=0.8)

    ax.set_title(
        "Change in Mean Land Surface Temperature",
        fontsize=14,
        fontweight="bold",
    )

    ax.set_ylabel("Temperature Difference (°C)")
    ax.grid(axis="y", linestyle="--", alpha=0.4)

    save_chart(
        fig,
        "lst_absolute_change.png",
    )


# ---------------------------------------------------------
# 8. DESCRIPTIVE TEMPORAL TRENDS
# ---------------------------------------------------------

def plot_descriptive_trends(trends):
    """
    Generate one descriptive slope chart per indicator.

    Slope values retain their original units per decade.
    Different indicators are not combined into one chart.
    """

    for _, row in trends.iterrows():

        indicator = row["indicator"]
        slope = float(row["slope_per_decade"])
        r_squared = float(row["r_squared_descriptive"])

        fig, ax = plt.subplots(figsize=(7, 4))

        bars = ax.bar(
            [indicator],
            [slope],
        )

        ax.axhline(0, linewidth=0.8)

        ax.bar_label(
            bars,
            fmt="%.5f",
            padding=4,
        )

        ax.set_title(
            f"{indicator} Descriptive Trend",
            fontsize=13,
            fontweight="bold",
        )

        ax.set_ylabel("Slope per Decade")
        ax.grid(axis="y", linestyle="--", alpha=0.4)

        ax.text(
            0.98,
            0.95,
            f"Descriptive R² = {r_squared:.3f}",
            transform=ax.transAxes,
            ha="right",
            va="top",
        )

        save_chart(
            fig,
            f"{indicator}_descriptive_slope.png",
        )


# ---------------------------------------------------------
# 9. MAIN VISUALIZATION PIPELINE
# ---------------------------------------------------------

def generate_all_visualizations():

    print("\n" + "=" * 60)
    print("NMMC ECOLOGICAL VISUALIZATION")
    print("=" * 60)

    annual, changes, trends = load_analysis_reports()

    print("\n[1/5] Generating indicator temporal charts...")
    plot_indicator_trends(annual)

    print("\n[2/5] Generating LST distribution chart...")
    plot_lst_distribution(annual)

    print("\n[3/5] Generating optical index change chart...")
    plot_optical_index_changes(changes)

    print("\n[4/5] Generating LST change chart...")
    plot_lst_change(changes)

    print("\n[5/5] Generating descriptive trend charts...")
    plot_descriptive_trends(trends)

    print("\n" + "=" * 60)
    print("VISUALIZATION COMPLETE")
    print("=" * 60)

    print(f"\nCharts directory: {CHARTS_DIR}")


# ---------------------------------------------------------
# 10. EXECUTION
# ---------------------------------------------------------

if __name__ == "__main__":
    generate_all_visualizations()
